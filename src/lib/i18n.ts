const DICTS: Record<Locale, Dict> = { en, de, ar };

export function deviceLocale(): Locale {
  try {
    const tag = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2).toLowerCase();
    return tag === 'de' || tag === 'ar' ? tag : 'en';
  } catch {
    return 'en';
  }
}

